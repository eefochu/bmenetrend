#!/usr/bin/env python3
"""Package an already generated archive and record its exact installed budget.

Does not test the app. Run after extract.py, tippecanoe, styles.py and fetching
licensed glyph/license files, as described in README.md.
"""
import hashlib
import json
from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'app/src/main/assets/map'
DATA = ASSETS / 'offline'
archive = Path(sys.argv[1])
if archive.stat().st_size > 50_000_000:
    raise SystemExit('Archive exceeds the 50 MB packaging budget; reduce detail before packaging.')
shutil.copyfile(archive, DATA / 'hungary.pmtiles')
files = sorted([p for p in DATA.rglob('*') if p.is_file() and p.name != 'manifest.json'] + [ASSETS / 'offline.json', ASSETS / 'offline-dark.json'])
entries = {str(p.relative_to(ASSETS)): {'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in files}
manifest = {
    'schema':1, 'source':'https://download.geofabrik.de/europe/hungary-261025.osm.pbf',
    'source_sha256':'95cee027cb022b35b6633c511119d72f19fb6a606e8c8eceba0de80709d66912',
    'license':'ODbL-1.0', 'minzoom':5, 'maxzoom':12, 'detail':12, 'files':entries,
}
(DATA / 'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
archive_entry = entries['offline/hungary.pmtiles']
bundled = sum(e['bytes'] for e in entries.values()) + (DATA / 'manifest.json').stat().st_size
installed = bundled + archive_entry['bytes']
kotlin = ROOT / 'app/src/main/java/hu/app/bmenetrend/map/OfflineBasemapAssets.kt'
kotlin.write_text('''package hu.app.bmenetrend.map

// Generated by tools/offline-map/package.py. Raw asset sizes are conservative:
// APK compression is not deducted. The local native file copy is counted too.
object OfflineBasemapAssets {
    const val ARCHIVE_BYTES = %dL
    const val ARCHIVE_SHA256 = "%s"
    const val BUNDLED_BYTES = %dL
    const val INSTALLED_BYTES = BUNDLED_BYTES + ARCHIVE_BYTES
}
''' % (archive_entry['bytes'],archive_entry['sha256'],bundled))
print(json.dumps({'archiveBytes':archive_entry['bytes'],'bundledBytes':bundled,'installedMapBytes':installed,'with388014080ByteTimetable':installed+388014080}))
